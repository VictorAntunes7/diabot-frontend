import AsyncStorage from '@react-native-async-storage/async-storage';

export type Idioma = 'pt' | 'en' | 'es';

const CHAVE_IDIOMA = 'idioma_app';

export async function salvarIdioma(idioma: Idioma) {
  await AsyncStorage.setItem(CHAVE_IDIOMA, idioma);
}

export async function obterIdioma(): Promise<Idioma> {
  const val = await AsyncStorage.getItem(CHAVE_IDIOMA);
  return (val as Idioma) ?? 'pt';
}

